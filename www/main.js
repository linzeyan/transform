function detectImageFormat(bytes, filename = '') {
    const ext = normalizeImageExt(filename.split('.').pop() || '');
    const magic = detectImageMagic(bytes);
    return magic || ext;
}

function normalizeImageExt(ext) {
    const lower = (ext || '').toLowerCase();
    switch (lower) {
        case 'jpg':
        case 'jpeg':
            return 'jpg';
        case 'png':
            return 'png';
        case 'webp':
            return 'webp';
        case 'avif':
            return 'avif';
        default:
            return '';
    }
}

function detectImageMagic(bytes) {
    if (!(bytes && bytes.length)) return '';
    // PNG signature: 89 50 4E 47 0D 0A 1A 0A
    if (
        bytes[0] === 0x89 &&
        bytes[1] === 0x50 &&
        bytes[2] === 0x4e &&
        bytes[3] === 0x47 &&
        bytes[4] === 0x0d &&
        bytes[5] === 0x0a &&
        bytes[6] === 0x1a &&
        bytes[7] === 0x0a
    ) {
        return 'png';
    }
    // JPEG starts with FF D8.
    if (bytes[0] === 0xff && bytes[1] === 0xd8) {
        return 'jpg';
    }
    if (bytes.length > 12) {
        const riff = String.fromCharCode(bytes[0], bytes[1], bytes[2], bytes[3]);
        const webp = String.fromCharCode(bytes[8], bytes[9], bytes[10], bytes[11]);
        if (riff === 'RIFF' && webp === 'WEBP') {
            return 'webp';
        }
        const box = String.fromCharCode(bytes[4], bytes[5], bytes[6], bytes[7]);
        const brand = String.fromCharCode(bytes[8], bytes[9], bytes[10], bytes[11]);
        if (box === 'ftyp') {
            if (['avif', 'avis', 'mif1', 'mvif'].includes(brand)) {
                return 'avif';
            }
        }
    }
    return '';
}

function imageMimeFromFormat(format) {
    switch ((format || '').toLowerCase()) {
        case 'png':
            return 'image/png';
        case 'jpg':
        case 'jpeg':
            return 'image/jpeg';
        case 'webp':
            return 'image/webp';
        case 'avif':
            return 'image/avif';
        default:
            return '';
    }
}

function formatByteSize(bytes) {
    if (!Number.isFinite(bytes) || bytes <= 0) return '0 B';
    const units = ['B', 'KB', 'MB', 'GB'];
    let value = bytes;
    let idx = 0;
    while (value >= 1024 && idx < units.length - 1) {
        value /= 1024;
        idx += 1;
    }
    const rounded = value >= 10 || value % 1 === 0 ? value.toFixed(0) : value.toFixed(1);
    return `${rounded} ${units[idx]}`;
}

