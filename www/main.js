function groupFingerprintFacts(facts) {
    const groups = new Map();
    [...facts]
        .sort((a, b) => a.group.localeCompare(b.group))
        .forEach((fact) => {
            if (!groups.has(fact.group)) groups.set(fact.group, []);
            groups.get(fact.group).push(fact);
        });
    return groups;
}

